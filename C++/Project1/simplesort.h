#pragma once
class simplesort
{
public:
    static int* BubbleSort(int arr[], int size) {
        return arr;
    }
    static int* SelectionSort(int arr[], int size) {
        return arr;
	}
    static int* InsertionSort(int arr[], int size) {
        return arr;
	}
    static void swap(int& a, int& b) {
        int temp = a;
		a = b;
		b = temp;
    }
};

